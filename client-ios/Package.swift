// swift-tools-version:5.9
import PackageDescription

// OpenSteerCore is Foundation-only: no CoreMotion, no Network, no UIKit. That
// lets the whole steering and wire-format contract be tested with `swift test`
// on any platform, including a CI box with no Apple frameworks, and it keeps the
// app target free to be rebuilt without touching the math.
let package = Package(
    name: "OpenSteerCore",
    platforms: [
        .iOS(.v17),
        .macOS(.v13),
    ],
    products: [
        .library(name: "OpenSteerCore", targets: ["OpenSteerCore"]),
    ],
    targets: [
        .target(
            name: "OpenSteerCore",
            swiftSettings: [
                .enableExperimentalFeature("StrictConcurrency")
            ]
        ),
        .testTarget(
            name: "OpenSteerCoreTests",
            dependencies: ["OpenSteerCore"],
            resources: [
                // The one conformance fixture, shared with the C# suite. It is
                // generated by tools/golden_vectors.py and copied here verbatim;
                // both copies are hash-compared in the build checklist.
                .copy("Fixtures/golden_vectors.json")
            ]
        ),
    ]
)
