import XCTest
@testable import OpenSteerCore

/// Encode speed: the budget is 2 microseconds per encode, which the whole 120 Hz
/// pipeline has to fit inside many times over. Run this in Release: a Debug build
/// measures unoptimized code and says nothing about the shipping app.
final class EncodePerformanceTests: XCTestCase {
    /// Ten thousand encodes into one preallocated slot, which is exactly what the
    /// send path does. The array is allocated once, outside the measured block.
    func testEncodeThroughput() {
        var slot = [UInt8](repeating: 0, count: UplinkCodec.size)
        var state = UplinkState(sequence: 0, steer: 0, throttle: 0, brake: 0,
                                clutch: 0, buttons: 0, timestampNs: 0)

        measure {
            slot.withUnsafeMutableBytes { raw in
                for i in 0..<10_000 {
                    state.sequence = UInt16(truncatingIfNeeded: i)
                    state.steer = Int16(truncatingIfNeeded: i &* 7)
                    state.timestampNs = UInt64(i) &* 8_333_333
                    UplinkCodec.encode(state, into: raw)
                }
            }
        }
    }

    /// The whole steering chain, end to end, at the rate the sensor delivers it.
    func testFullPipelineThroughput() {
        var extractor = TwistExtractor()
        var unwrapper = AngleUnwrapper()
        let mapper = SteerMapper(dor: .dor360)
        var slot = [UInt8](repeating: 0, count: UplinkCodec.size)
        var state = UplinkState()

        measure {
            slot.withUnsafeMutableBytes { raw in
                for i in 0..<10_000 {
                    let angle = Double(i % 720) * 0.5
                    let theta = extractor.step(reference: .identity,
                                               current: Quat.rz(angle))
                    let continuous = unwrapper.step(theta)
                    state.steer = mapper.steer(continuousDegrees: continuous)
                    state.sequence &+= 1
                    UplinkCodec.encode(state, into: raw)
                }
            }
        }
    }

    /// The encode budget, asserted rather than only recorded.
    ///
    /// `measure` writes its result into a baseline stored inside the .xcodeproj,
    /// and that project is generated by XcodeGen and never committed, so the
    /// number it captures is thrown away on every clean checkout. This is the
    /// same work with an assertion attached, so a regression fails the test. The
    /// budget is 20 ms for ten thousand encodes, which is 2 us each, and the real
    /// cost is far below that: the margin is there so a busy continuous
    /// integration machine does not fail the build for being busy.
    func testEncodeMeetsTheTimeBudget() {
        var slot = [UInt8](repeating: 0, count: UplinkCodec.size)
        var state = UplinkState()

        // One throwaway pass first. The first call through a method runs in an
        // unoptimized tier, and measuring that would measure the warm-up.
        slot.withUnsafeMutableBytes { raw in
            for _ in 0..<10_000 { UplinkCodec.encode(state, into: raw) }
        }

        var best = Double.greatestFiniteMagnitude
        for _ in 0..<5 {
            let start = DispatchTime.now().uptimeNanoseconds
            slot.withUnsafeMutableBytes { raw in
                for i in 0..<10_000 {
                    state.sequence = UInt16(truncatingIfNeeded: i)
                    UplinkCodec.encode(state, into: raw)
                }
            }
            let elapsedMs = Double(DispatchTime.now().uptimeNanoseconds - start) / 1e6
            best = min(best, elapsedMs)
        }

        XCTAssertLessThanOrEqual(best, 20.0,
                                 "10 000 encodes took \(best) ms, budget is 20 ms")
    }

    /// A guard rail rather than a benchmark: if one encode ever takes a
    /// millisecond, something has started allocating or locking on the hot path.
    func testSingleEncodeIsNowhereNearAMillisecond() {
        var slot = [UInt8](repeating: 0, count: UplinkCodec.size)
        let state = UplinkState(sequence: 1, steer: -12345, throttle: 65535,
                                brake: 1, clutch: 2, buttons: 7,
                                timestampNs: 123_456_789)

        var worst: Double = 0
        slot.withUnsafeMutableBytes { raw in
            for _ in 0..<2000 {
                let start = DispatchTime.now().uptimeNanoseconds
                UplinkCodec.encode(state, into: raw)
                let elapsed = Double(DispatchTime.now().uptimeNanoseconds - start)
                worst = max(worst, elapsed)
            }
        }

        XCTAssertLessThan(worst, 1_000_000, "worst single encode was \(worst) ns")
    }
}
